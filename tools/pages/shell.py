"""Shared page shell for the Mawkeb site's inner pages.

The site is plain HTML. Pages under tools/pages/ describe each inner page's content; running
`python tools/pages/build.py` writes the .html files. Editing a generated .html file by hand also works,
but the next build would overwrite it, so make lasting edits in tools/pages/."""

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title}</title>
<meta name="description" content="{desc}">
<meta name="theme-color" content="#121309">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<meta property="og:image" content="{og}">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Montserrat:wght@400;500;600;700&display=swap" rel="stylesheet">
<link rel="icon" href="/assets/brand/icon-192.png">
<link rel="stylesheet" href="/assets/site/site.css">
</head>
<body{body_attrs}>
<!-- Generated by tools/pages/build.py from tools/pages/content.py. Edit the content there. -->
<a class="skip" href="#main">Skip to content</a>
<header id="site-header"></header>
<main id="main">
"""

FOOT = """</main>
<footer id="site-footer"></footer>
<script src="/assets/site/config.js"></script>
<script src="/assets/site/site.js"></script>
{scripts}</body>
</html>
"""


def esc(s):
    return s.replace('&', '&amp;').replace('"', '&quot;').replace('<', '&lt;')


def page(title, desc, body, og='/assets/media/archive/1448-majlis-2.jpg', body_attrs='', scripts=''):
    return (HEAD.format(title=esc(title), desc=esc(desc), og=og, body_attrs=body_attrs)
            + body + FOOT.format(scripts=scripts))


def hero(title, lede, crumbs, img=None, ar=None, ctas='', img_pos='50% 50%', img_alt=''):
    """crumbs: list of (href, label); the last item is the current page (no link)."""
    cr = ''.join('<li><a href="%s">%s</a></li>' % c for c in crumbs[:-1]) + '<li aria-current="page">%s</li>' % crumbs[-1][1]
    bg = ''
    if img:
        bg = '<img class="bg" src="%s" alt="%s" style="object-position:%s"><div class="shade"></div>' % (img, img_alt, img_pos)
    return ('<section class="page-hero%s">%s<div class="wrap">'
            '<nav aria-label="Breadcrumb"><ol class="crumbs">%s</ol></nav>'
            '<h1>%s</h1>%s<p class="lede">%s</p>%s</div></section>\n') % (
        ' has-img' if img else '', bg, cr, title,
        ('<span class="ar ar-title" lang="ar" dir="rtl" style="text-align:left">%s</span>' % ar) if ar else '',
        lede, ('<div class="ctas">%s</div>' % ctas) if ctas else '')


def gallery(items, cls='gallery'):
    """items: list of (src, caption[, extra class])"""
    out = []
    for it in items:
        src, cap = it[0], it[1]
        extra = (' class="%s"' % it[2]) if len(it) > 2 else ''
        out.append('<button type="button"%s data-full="%s" data-cap="%s"><img loading="lazy" src="%s" alt="%s"><span class="cap">%s</span></button>'
                   % (extra, src, esc(cap), src, esc(cap), cap))
    return '<div class="%s" data-gallery>%s</div>' % (cls, ''.join(out))


def pager(prev, nxt):
    p = ('<a class="prev" href="%s"><small>Previous program</small><b>%s</b></a>' % prev) if prev else '<span></span>'
    n = ('<a class="next" href="%s"><small>Next program</small><b>%s</b></a>' % nxt) if nxt else '<span></span>'
    return '<section class="sec tight"><div class="wrap"><nav class="pager" aria-label="More programs">%s%s</nav><p style="margin-top:20px"><a class="text-link" href="/programs/">All programs</a></p></div></section>\n' % (p, n)
